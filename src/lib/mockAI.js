import { MODELS } from '../data/plans.js'

const sleep = (ms) => new Promise((r) => setTimeout(r, ms))

export function getModel(modelId) {
  return MODELS.find((m) => m.id === modelId) || MODELS[0]
}

export async function generateChatReply({ prompt, modelId, history }) {
  const model = getModel(modelId)
  await sleep(700 + Math.random() * 900)
  const topic = prompt.trim().replace(/\s+/g, ' ').slice(0, 80)
  const followups = history && history.length > 2
  return [
    `**${model.name}** — here's a take on “${topic}”:`,
    '',
    'A good starting point is to break this into what you already know, what you need to verify, and the smallest next step that produces a useful result. From there:',
    '',
    '1. **Frame the goal** in one sentence so every decision maps back to it.',
    '2. **Gather the constraints** — time, budget, tooling, and who has to approve.',
    '3. **Draft, then critique** — produce a rough answer first, refine against the constraints.',
    '',
    followups
      ? 'I can build on the earlier messages in this conversation if you want me to adjust the direction.'
      : 'Tell me more about your context and I’ll tailor this further.',
  ].join('\n')
}

export async function generateImage({ prompt }) {
  await sleep(1400 + Math.random() * 1200)
  // Deterministic gradient SVG "generated image" tied to the prompt
  let hash = 0
  for (const ch of prompt) hash = (hash * 31 + ch.charCodeAt(0)) >>> 0
  const h1 = hash % 360
  const h2 = (h1 + 60 + (hash % 120)) % 360
  const svg = `<svg xmlns='http://www.w3.org/2000/svg' width='768' height='512'>
    <defs><linearGradient id='g' x1='0' y1='0' x2='1' y2='1'>
      <stop offset='0%' stop-color='hsl(${h1},70%,62%)'/>
      <stop offset='100%' stop-color='hsl(${h2},65%,45%)'/>
    </linearGradient></defs>
    <rect width='768' height='512' fill='url(#g)'/>
    <circle cx='${120 + (hash % 400)}' cy='${100 + (hash % 250)}' r='${60 + (hash % 90)}' fill='hsla(${h2},80%,85%,0.35)'/>
    <circle cx='${500 - (hash % 300)}' cy='${380 - (hash % 160)}' r='${40 + (hash % 60)}' fill='hsla(${h1},80%,20%,0.3)'/>
    <text x='24' y='488' font-family='sans-serif' font-size='18' fill='rgba(255,255,255,0.85)'>Mellow Image · ${prompt.slice(0, 48).replace(/[<>&"]/g, '')}</text>
  </svg>`
  return { dataUrl: 'data:image/svg+xml;utf8,' + encodeURIComponent(svg), width: 768, height: 512 }
}

export async function generateCode({ prompt }) {
  await sleep(900 + Math.random() * 900)
  const name = (prompt.match(/\b(\w+)\b/g) || ['snippet']).slice(-1)[0].toLowerCase().replace(/[^a-z]/g, '') || 'snippet'
  const fn = name.charAt(0).toUpperCase() + name.slice(1)
  const code = `// Generated by Mellow Coder — request: "${prompt.slice(0, 60)}"
export function use${fn}(initialState = {}) {
  const [state, setState] = React.useState(initialState);

  const update = React.useCallback((patch) => {
    setState((prev) => ({ ...prev, ...patch }));
  }, []);

  const reset = React.useCallback(() => setState(initialState), [initialState]);

  return { state, update, reset };
}`
  const explanation = 'This hook wraps local component state with a stable `update` helper (shallow merge) and a `reset`. Memoized callbacks keep it safe to pass down as props without extra re-renders.'
  return { language: 'jsx', code, explanation }
}

export async function generateFeedback({ prompt }) {
  await sleep(1000 + Math.random() * 800)
  return {
    summary: 'Solid overall structure with clear intent. A few targeted improvements would raise quality noticeably.',
    strengths: ['Clear goal statement up front', 'Logical ordering of ideas', 'Concrete examples where it matters most'],
    improvements: [
      { area: 'Specificity', note: 'Replace vague qualifiers (“good”, “fast”) with measurable targets.' },
      { area: 'Audience fit', note: 'Define who reads this and cut detail that doesn’t serve them.' },
      { area: 'Call to action', note: 'End with exactly one next step the reader can take today.' },
    ],
    score: 7 + (prompt.length % 3), // 7–9 / 10
  }
}
